def _strip_tags(text: str) -> str:
    """What the game shows after removing rich/custom tags (<@..>, <$..>, <color>...)."""
    return RICH_TEXT_TAG_RE.sub("", text)

TARGET_LANG = "ru"
SOURCE_LOCALE = "en"


def _macro_key(token: str) -> str:
    """Normalize one {macro} so {@nickname} == {nickname} == {Nickname}."""
    return token.strip("{}").lstrip("@").split(":")[0].casefold()


def _macro_tokens(text: str) -> list[str]:
    return [_macro_key(m) for m in MACRO_RE.findall(text)]


TAG_OPT = r"(?:<[^>]*>)?"
# Tag-tolerant literals balloon patterns 3-5x and hang the game at login
# (proven: simple patterns work, tag-tolerant white-screen). Keep OFF until
# a bounded variant is proven safe in-game. Simple patterns still match tags
# *inside* macro captures (numbers/names), which covers most skills.
TAG_TOLERANT = False


def _canon_source(text: str) -> str:
    """Unify keys that can only ever match the same runtime text.

    - Real CR chars: the game normalizes newlines before display.
    - Macro name case/format: macros are substituted before matching.
    """
    text = text.replace("\r", "")
    return MACRO_RE.sub(lambda m: "{" + m.group(0)[1:-1].casefold() + "}", text)


def _squash_tags(pattern: str) -> str:
    doubled = TAG_OPT + TAG_OPT
    while doubled in pattern:
        pattern = pattern.replace(doubled, TAG_OPT)
    return pattern


def _rx_lit(text: str) -> str:
    """Escape a literal for the SIMPLE (proven-safe) regex form, plus:

    - ``<@tag>`` -> also matches resolved ``<color...>`` (the game swaps
      ``<@ba.vup>`` etc. for real ``<color=#..>`` before XUnity sees text;
      ground truth: _AutoGeneratedTranslations keys carry ``<color>``).
    - ``</>`` -> also matches ``</color>``.
    - ``<color=#..>`` with hardcoded params -> generalized params.
    - Any whitespace/tag run between words -> SEP, which matches spaces,
      newlines, literal backslash-n sequences and stray tags in any mix.
      Tag placement drifts between data versions (Leizi S3: live text has
      ``<@ba.vup>bounce back</>`` where our template has bare words),
      and tags hug words with no space around them, so every literal
      word also accepts one adjacent tag on each side. All repetitions
      are atomic and prefix-deterministic (no catastrophic backtracking).
    """
    # separator: whitespace, literal backslash-n, or any single tag
    sep = r'(?>\s|\\n|<[^>]*>)+'
    # optional single tag hugging a word
    tago = r'(?><[^<>]*>)?'
    out: list[str] = []
    for i, part in enumerate(re.split(r'(<[^<>]*>|\s+)', text)):
        if not part:
            continue
        if i % 2 == 1:
            if part.strip() == '':
                out.append(sep)
            elif part == '</>':
                out.append('(?:</>|</color>)')
            elif part.startswith('<@') or part.startswith('<$'):
                out.append('(?:' + re.escape(part) + r'|<color\b[^<>]*>)')
            elif part.lower().startswith('<color'):
                out.append(r'<color\b[^<>]*>')
            else:
                out.append(re.escape(part))
        else:
            # tags also squeeze between a word and adjacent punctuation
            # (live 'expands</>,' vs template 'expands,'), so hug every
            # alnum/punct run with optional tags, not just whole tokens
            for w in re.findall(r'\w+|[^\w\s]', part):
                out.append(tago + re.escape(w) + tago)
    return ''.join(out)


def _macro_regex_pair(source: str, target: str) -> tuple[str, str] | None:
    """Build a bounded XUnity regex for a template pair with {macros}.

    The game substitutes macros (player name, skill numbers) BEFORE XUnity
    sees the text, so exact template entries can never match at runtime.
    Positional captures preserve argument order. Literals are emitted
    by _rx_lit (raw tags + <color> alternatives + backslash-n tolerance),
    captures never cross angle brackets (see _rx_lit).
    """
    if source.startswith(("r:", "sr:")):
        return None
    src_toks = MACRO_RE.findall(source)
    if not src_toks:
        return None
    tgt_toks = MACRO_RE.findall(target)
    if [_macro_key(m) for m in src_toks] != [_macro_key(m) for m in tgt_toks]:
        return None
    literal = MACRO_RE.sub("", source)
    if len("".join(literal.split())) < 12:
        return None
    parts: list[str] = []
    cursor = 0
    order: list[str] = []
    for i, m in enumerate(MACRO_RE.finditer(source)):
        lit = source[cursor:m.start()]
        parts.append(_rx_lit(lit))
        tag = f"p{i}"
        # Values arrive wrapped in highlight tags (<@ba.vup> or resolved
        # <color=#..>). One atomic-optional tag on each side of the capture;
        # atomicity keeps failure paths linear (no white-screen hang).
        parts.append(rf"(?><[^<>]*>)?(?<{tag}>[^<>]*?)(?><[^<>]*>)?")
        order.append(tag)
        cursor = m.end()
    tail = source[cursor:]
    parts.append(_rx_lit(tail))
    # Replacement goes straight to the display, bypassing the game's own
    # <@tag> resolution (it runs before XUnity sees the text). Raw <@..>
    # wrappers in the output would stay visible (proven in-game), so strip
    # <@..>..</> pairs and lone <@..> openers. <color>/<i> survive: the
    # renderer understands them, and their </> closers are kept.
    tgt_clean = re.sub(r"<@[^\r\n<>]*>(.*?)</>", r"\1", target)
    tgt_clean = re.sub(r"<@[^\r\n<>]*>", "", tgt_clean)
    repl: list[str] = []
    cursor = 0
    idx = 0
    for m in MACRO_RE.finditer(tgt_clean):
        repl.append(tgt_clean[cursor:m.start()].replace("$", "$$"))
        repl.append("${" + order[idx] + "}")
        idx += 1
        cursor = m.end()
    repl.append(tgt_clean[cursor:].replace("$", "$$"))
    return 'r:"\\A' + _squash_tags("".join(parts)) + '\\z"', '"' + "".join(repl) + '"'


def _extract_pairs(data: Any, origin: str) -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    if isinstance(data, dict):
        items = data.items()
        for k, v in items:
            if isinstance(k, str) and isinstance(v, str):
                pairs.append((k, v))
            elif isinstance(v, dict):
                for sk in ("target", "ru", "translation", "text"):
                    if isinstance(v.get(sk), str):
                        src = v.get("source", v.get("en", k))
                        if isinstance(src, str):
                            pairs.append((src, v[sk]))
                        break
    elif isinstance(data, list):
        for item in data:
            if not isinstance(item, dict):
                continue
            src = item.get("source", item.get("en"))
            dst = item.get("target", item.get("ru", item.get("translation")))
            if isinstance(src, str) and isinstance(dst, str):
                pairs.append((src, dst))
    return pairs


def strip_display_tags(t: str) -> str:
    # Raw <@..>/<$..> in the output would stay visible: the game
    # resolves tags before XUnity sees the text, bypassing its own
    # resolution on the way out. Strip <@..>/<$..> pairs, lone openers
    # and dangling </> (whose opener was a display tag). <color>/<i>/<b>
    # survive: the renderer understands them. Applied centrally so no
    # source can reintroduce raw tags on rebuilds.
    t = re.sub(r'<[@$][^\r\n<>]*>(.*?)</>', r'\1', t)
    t = re.sub(r'<[@$][^\r\n<>]*>', '', t)
    parts = re.split(r'(</>)', t)
    out = []
    for i, part in enumerate(parts):
        if part != '</>':
            out.append(part)
            continue
        prev = ''.join(out)
        toks = re.findall(r'<[^<>]*>', prev)
        keep = toks and toks[-1].lower().startswith(('<color', '<i>', '<i ', '<b>', '<b '))
        out.append('</>' if keep else '')
    return ''.join(out)


def load_merged(manifest_dir: Path) -> tuple[dict[str, str], Counter, list]:
    """Single source of truth: manifests + tag-free variants + overrides + IDs.

    Used by the hook pack builder AND the file-replacement scripts, so both
    see identical translations.
    """
    manifest_dir = manifest_dir.expanduser().resolve()
    files = sorted(manifest_dir.glob("*.json"))
    if not files:
        raise FileNotFoundError(f"No *.json manifests in {manifest_dir}")
    merged: dict[str, str] = {}
    conflicts: list[dict[str, str]] = []
    skipped = Counter()
    unwrapped = 0

    def _detagged(counter: Counter) -> Counter:
        return Counter({k: v for k, v in counter.items()
                        if not (isinstance(k, str) and RICH_TEXT_TAG_RE.fullmatch(k))})

    def _strip_display_tags(t: str) -> str:
        return strip_display_tags(t)

    def _ingest(s: str, t: str, origin: str) -> None:
        nonlocal unwrapped
        if not s or not t or s == t:
            skipped["empty_or_identical"] += 1
            return
        # Display-hint tags (<@ba.vup>, </>, <color>) are not placeholders:
        # RU values ship tag-stripped (raw <@..> would stay visible: the
        # game resolves tags before XUnity sees the text, bypassing its
        # own resolution on the way out). Compare placeholder sets
        # tag-blind so stripped values are not dropped as mismatched.
        if _detagged(placeholder_counter(s)) != _detagged(placeholder_counter(t)):
            # {@x} and {x} are the same runtime value (game strips @).
            if Counter(_macro_tokens(s)) != Counter(_macro_tokens(t)) or not MACRO_RE.search(s):
                skipped["placeholder_mismatch"] += 1
                return
        if HAN_RE.search(t):
            # RU targets must not contain Chinese (mixed untranslated leftovers).
            skipped["target_has_han"] += 1
            return
        if s in merged and merged[s] != t:
            conflicts.append({"source": s, "kept": merged[s], "dropped": t, "file": origin})
            skipped["conflict"] += 1
            return
        merged[s] = t

    # Tag-free variants are collected for EVERY pair (even conflict losers)
    # and ingested in a second phase, sorted by key, only for absent keys.
    # This makes the result independent of manifest split/order, so a frozen
    # single-file manifest rebuilds byte-identically.
    variant_candidates: list[tuple[str, str, str]] = []
    for path in files:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
        for src, dst in _extract_pairs(data, path.name):
            s = _canon_source(normalize_lookup_text(src))
            t = dst.strip()
            fixed = _unwrap_quotes(s, t)
            if fixed != t:
                unwrapped += 1
                t = fixed
            t = _strip_display_tags(t)
            _ingest(s, t, path.name)
            # Tag-free variant: the game strips rich/custom tags before display,
            # so "<$ba.stun>Stuns</> +{atk:0%}" is shown as "Stuns +120%".
            ss = _canon_source(normalize_lookup_text(_strip_tags(src)))
            st = _strip_tags(dst).strip()
            st = _unwrap_quotes(ss, st)
            if (ss != s or st != t) and ss and st:
                variant_candidates.append((ss, st, path.name + ":display"))
    for ss, st, origin in sorted(variant_candidates):
        _ingest(ss, st, origin)
    # ru-overrides/: hand-written fixes win over TSV (typos like Стоимос,
    # missing strings). Files: {"English": "Русский"} or [{source,target}].
    # Name them 00_*.json to keep them first if you ever reconvert.
    overrides_dir = manifest_dir.parent / "ru-overrides"
    overridden = 0
    if overrides_dir.is_dir():
        for path in sorted(overrides_dir.glob("*.json")):
            data = json.loads(path.read_text(encoding="utf-8-sig"))
            for src, dst in _extract_pairs(data, path.name):
                s = normalize_lookup_text(src)
                t = _strip_display_tags(_unwrap_quotes(s, dst.strip()))
                if not s or not t or s == t or HAN_RE.search(t):
                    continue
                if _detagged(placeholder_counter(s)) != _detagged(placeholder_counter(t)):
                    if Counter(_macro_tokens(s)) != Counter(_macro_tokens(t)) or not MACRO_RE.search(s):
                        continue
                if s in merged and merged[s] != t:
                    overridden += 1
                merged[s] = t
    # ID-authoritative operator names (tools/build_ru_context.py): win over
    # heuristic single-token entries, unwrapped ("Snowsant" not «"Сноусант"»).
    id_names = manifest_dir.parent / "work" / "13_names_from_ids.json"
    id_overridden = 0
    if id_names.is_file():
        for en, ru in json.loads(id_names.read_text(encoding="utf-8-sig")).items():
            s, t = normalize_lookup_text(en), ru.strip().strip("«»\"\"''")
            if not s or not t or s == t or " " in s or HAN_RE.search(t):
                continue
            if s in merged and merged[s] != t:
                id_overridden += 1
            merged[s] = t
    skipped["unwrapped_quotes"] = unwrapped
    skipped["overridden_by_ru_overrides"] = overridden
    skipped["id_names_applied"] = id_overridden
    if not merged:
        raise ValueError("Custom manifests contain no usable EN->RU pairs")
    # Hand-filled story gaps (work/story_ru.tsv: kind/asset/english/russian).
    story_tsv = manifest_dir.parent / "work" / "story_ru.tsv"
    if story_tsv.is_file():
        import csv
        with open(story_tsv, encoding="utf-8-sig", newline="") as f:
            rd = csv.reader(f, delimiter="\t")
            header = next(rd, None)
            cols = {c.strip().lower(): i for i, c in enumerate(header or [])}
            ie, ir = cols.get("english", 2), cols.get("russian", 3)
            n = 0
            for row in rd:
                if len(row) <= max(ie, ir):
                    continue
                s = _canon_source(normalize_lookup_text(row[ie]))
                t = row[ir].strip()
                if s and t and s != t:
                    if s not in merged:
                        n += 1
                    merged[s] = t
        skipped["story_tsv_applied"] = n
    return merged, skipped, conflicts


def build_custom_pack(manifest_dir: Path, output_root: Path) -> dict[str, Any]:
    merged, skipped, conflicts = load_merged(Path(manifest_dir))
    pairs = sorted(merged.items(), key=lambda p: (p[0].casefold(), p[0]))
    text_root = output_root / "Translation" / TARGET_LANG / "Text"
    # Split into parts so a bad category can be disabled by deleting one file:
    # 11_ui.txt = short single-line UI strings (safe set);
    # 12_story.txt = long/multi-line story;
    # 13_names.txt = EXPERIMENTAL single-token display names (operators etc.).
    # Names can be logic keys for the game (cf. enemy-table incident), so this
    # file ships separately: copy it into the game only to test, remove on hang.
    ident_re = re.compile(r"[A-Za-z0-9_'\-.]+")
    names = [(s, t) for s, t in pairs if " " not in s and "\n" not in s and ident_re.fullmatch(s)]
    rest = [(s, t) for s, t in pairs if (s, t) not in set(names)]
    ui = [(s, t) for s, t in rest if "\n" not in s and len(s) <= 120 and len(t) <= 200]
    ui_set = set(ui) | set(names)
    story = [(s, t) for s, t in pairs if (s, t) not in ui_set]
    write_translation_file(text_root / "11_ui.txt", ui, "Arknights EN -> RU (UI, short strings)")
    write_translation_file(text_root / "12_story.txt", story, "Arknights EN -> RU (story/long strings)")
    write_translation_file(text_root / "13_names.txt", names, "Arknights EN -> RU (EXPERIMENTAL display names)")
    # 14_regex.txt = runtime-substituted templates ({@nickname}, skill numbers).
    # The game replaces macros before XUnity sees text, so only regex can match.
    # Templates that tools/build_skill_direct.py expanded into concrete variants
    # are excluded: they are served by the direct hash lookups instead, which
    # keeps the regex file small (its compile/match cost caused long freezes).
    regex_exclude: set[str] = set()
    exclude_path = manifest_dir.parent / "work" / "regex_exclude.json"
    if exclude_path.is_file():
        for item in json.loads(exclude_path.read_text(encoding="utf-8-sig")):
            if isinstance(item, str) and item:
                regex_exclude.add(item)
                regex_exclude.add(_canon_source(normalize_lookup_text(item)))
    regex_map: dict[str, str] = {}
    regex_conflicts = 0

    def _add_regex(rs: str, rt: str) -> None:
        nonlocal regex_conflicts
        if rs in regex_map and regex_map[rs] != rt:
            regex_conflicts += 1
            return
        regex_map[rs] = rt

    for s, t in pairs:
        if s in regex_exclude:
            skipped["regex_excluded"] += 1
            continue
        hit = _macro_regex_pair(s, t)
        if hit is None:
            continue
        rs, rt = hit
        _add_regex(rs, rt)
    # No built-in patterns: "Elite {0} Lv. {1}" and "{0} sec" are handled by the
    # RichTextFix dynamic rules (src/plugins/.../DynamicTranslations.cs), so
    # 14_regex.txt stays empty and XUnity never runs a regex sweep.
    regex_pairs = sorted(regex_map.items())
    write_translation_file(text_root / "14_regex.txt", regex_pairs,
                           "Arknights EN -> RU (macro templates as regex)")
    skipped["regex_emitted"] = len(regex_pairs)
    skipped["regex_conflicts"] = regex_conflicts
    old_single = text_root / "10_custom.txt"
    if old_single.is_file():
        old_single.unlink()
    report = {
        "source_locale": SOURCE_LOCALE,
        "target_locale": TARGET_LANG,
        "manifest_dir": str(manifest_dir),
        "manifest_files": sorted(p.name for p in Path(manifest_dir).glob("*.json")),
        "mappings": len(pairs),
        "skipped": dict(skipped),
        "conflicts": conflicts[:100],
    }
    write_json(output_root / "pack-report.json", report)
    validation = validate_translation_pack(output_root, TARGET_LANG)
    report["validation"] = {"ok": validation["ok"], "mappings": validation["mappings"]}
    write_json(output_root / "pack-report.json", report)
    if not validation["ok"]:
        raise ValueError(f"Custom pack validation failed: {validation['errors'][:3]}")
    return report
