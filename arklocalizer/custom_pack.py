"""Build EN->RU XUnity packs from simple user JSON manifests."""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path
from typing import Any

HAN_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")
MACRO_RE = re.compile(r"\{[^{}\r\n]+\}")
# Wrapping quotes the TSV translators overused on UI labels: «...», "...".
WRAP_PAIRS = (("«", "»"), ('"', '"'), ("\u201c", "\u201d"), ("\u201e", "\u201c"))


def _unwrap_quotes(source: str, target: str) -> str:
    """Drop outer wrapping quotes from target when source has none.

    Fixes «Элитный», «Смена» on buttons: translators wrapped bare UI labels
    in print-style quotes. Dialogue keeps its quotes (source has them too or
    quotes are inside the string, not wrapping the whole target).
    """
    t = target.strip()
    # Double print-style wrapping (««...».», ««...»») is always an artefact:
    # collapse it to a single layer.
    while (t.startswith("««") and t.endswith("»")
           and t.count("«") == t.count("»")):
        t = t[1:-1].strip()
    # A common TSV artefact is «...». : the whole sentence is wrapped, but the
    # closing quote is followed by the sentence punctuation, so the simple
    # startswith/endswith check below misses it.
    wrapped = re.fullmatch(r"«(.*)»([.,!?…]?)", t, re.S)
    if (wrapped and not re.search(r"[«»“”„]", source)
            and not (source[:1] in "'\"‘’" and source[-1:] in "'\"‘’")):
        inner = wrapped.group(1).strip()
        if inner and "«" not in inner and "»" not in inner:
            t = inner + wrapped.group(2)
    # Repeat to a fixpoint: translators nest wrappers ('"«...»"').
    # Single-file rebuilds must be stable (stored value re-ingested as-is).
    while True:
        for left, right in WRAP_PAIRS:
            if len(t) >= 3 and t.startswith(left) and t.endswith(right):
                inner = t[len(left):-len(right)].strip()
                source_wrapped = bool(source) and source[0] in "'\"\u2018\u2019\u201c\u201d\u201e\u00ab\u00bb" \
                    and source[-1] in "'\"\u2018\u2019\u201c\u201d\u201e\u00ab\u00bb"
                if (inner and left not in inner and right not in inner
                        and left not in source and right not in source
                        and (left != "\u00ab" or not source_wrapped)):
                    t = inner
                    break
        else:
            return t

from .util import RICH_TEXT_TAG_RE, normalize_lookup_text, placeholder_counter, write_json
